#!/usr/bin/env python3
"""Write the benchmark's task table and statistics macros from the pack zip.

    python scripts/benchmark_to_tex.py --pack benchmark/socgraph-21-v1.1.zip --out paper
"""

from __future__ import annotations

import argparse
import collections
import json
import statistics
import zipfile
from pathlib import Path


def esc(s: str) -> str:
    return (s.replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("&", "\\&")
            .replace("%", "\\%").replace("#", "\\#").replace("$", "\\$"))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pack", type=Path, default=Path("benchmark/socgraph-21-v1.1.zip"))
    ap.add_argument("--out", type=Path, default=Path("paper"))
    a = ap.parse_args()
    z = zipfile.ZipFile(a.pack)
    m = json.loads(z.read("manifest.json"))
    tasks = m["tasks"]
    answers = {t["id"]: json.loads(z.read(f"answers/{t['id']}.json")) for t in tasks}
    etypes, rtypes = collections.Counter(), collections.Counter()
    for t in tasks:
        g = json.loads(z.read(f"tasks/{t['id']}.json"))["graph"]
        etypes.update(e["type"] for e in g["entities"].values())
        rtypes.update(r["type"] for r in g["relations"].values())

    lines = [
        "\\begin{table*}[t]\\centering\\scriptsize",
        "\\caption{The 21 tasks of \\bench. Graph size is entities/relations; \\emph{Core} is the number of "
        "core entities (malicious) or legitimacy anchors (benign) in the ground truth.}",
        "\\label{tab:tasks}",
        "\\begin{tabular}{@{}lllllrr@{}}\\toprule",
        "Task & OS & Verdict & ATT\\&CK & Alert title & Graph & Core\\\\\\midrule",
    ]
    for t in tasks:
        lines.append(
            f"\\texttt{{{esc(t['id'])}}} & {t['platform'][:3].capitalize()} & {t['verdict']} & "
            f"{esc(t['attack'])} & {esc(t['title'])} & {t['entities']}/{t['relations']} & "
            f"{len(answers[t['id']]['core'])}\\\\")
    lines += ["\\bottomrule\\end{tabular}\\end{table*}"]
    (a.out / "tables").mkdir(parents=True, exist_ok=True)
    (a.out / "tables" / "tasks.tex").write_text("\n".join(lines) + "\n")

    ents = [t["entities"] for t in tasks]
    rels = [t["relations"] for t in tasks]
    c = collections.Counter((t["platform"], t["verdict"]) for t in tasks)
    macros = {
        "BenchTasks": len(tasks),
        "BenchWinMal": c[("windows", "malicious")], "BenchWinBen": c[("windows", "benign")],
        "BenchLinMal": c[("linux", "malicious")], "BenchLinBen": c[("linux", "benign")],
        "BenchTechniques": len({t["attack"] for t in tasks if t["attack"] != "-"}),
        "BenchEntMin": min(ents), "BenchEntMax": f"{max(ents):,}".replace(",", "{,}"),
        "BenchEntMedian": int(statistics.median(ents)),
        "BenchRelMin": min(rels), "BenchRelMax": f"{max(rels):,}".replace(",", "{,}"),
        "BenchRelMedian": int(statistics.median(rels)),
        "BenchEntTypes": len(etypes), "BenchRelTypes": len(rtypes),
        "BenchZipMB": f"{a.pack.stat().st_size / 1e6:.2f}",
    }
    out = ["% Generated by scripts/benchmark_to_tex.py; do not edit by hand."]
    out += [f"\\providecommand{{\\{k}}}{{}}\\renewcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    (a.out / "benchmark_macros.tex").write_text("\n".join(out) + "\n")
    tl = ["% Entity and relation types across the benchmark (generated).",
          "\\begin{table}[t]\\centering\\scriptsize",
          "\\caption{Entity and relation types across \\bench (counts over all tasks).}",
          "\\label{tab:types}",
          "\\begin{tabular}{@{}lr@{\\hspace{1.2em}}lr@{}}\\toprule",
          "Entity type & Count & Relation type & Count\\\\\\midrule"]
    e_items, r_items = etypes.most_common(), rtypes.most_common()
    for i in range(max(len(e_items), len(r_items))):
        e = e_items[i] if i < len(e_items) else ("", "")
        r = r_items[i] if i < len(r_items) else ("", "")
        tl.append(f"\\texttt{{{esc(e[0])}}} & {e[1]} & \\texttt{{{esc(r[0])}}} & {r[1]}\\\\"
                  if e[0] else f" & & \\texttt{{{esc(r[0])}}} & {r[1]}\\\\")
    tl += ["\\bottomrule\\end{tabular}\\end{table}"]
    (a.out / "tables" / "types.tex").write_text("\n".join(tl) + "\n")
    print(json.dumps(macros))


if __name__ == "__main__":
    main()
